// Writes packages/adapters/python/src/stdlib.generated.ts: the union of the
// top-level standard-library module names of CPython 3.10 to 3.14, from each
// release's own generated list (Python/stdlib_module_names.h, which also
// backs sys.stdlib_module_names). Epoch never asks a Python interpreter
// (ADR-006), so the list ships as data.
//
// Usage (the script itself makes no network calls; fetch the inputs first):
//   curl -sSLO https://raw.githubusercontent.com/python/cpython/<tag>/Python/stdlib_module_names.h
//   node scripts/gen-python-stdlib.mjs <tag>=<path to that file> ...
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const inputs = process.argv.slice(2).map((arg) => {
  const eq = arg.indexOf("=");
  if (eq < 1) throw new Error(`expected <tag>=<path>, got ${arg}`);
  return { tag: arg.slice(0, eq), file: arg.slice(eq + 1) };
});
if (inputs.length === 0) {
  throw new Error("usage: gen-python-stdlib.mjs <tag>=<path> ...");
}

const names = new Set();
const sources = [];
for (const { tag, file } of inputs) {
  const bytes = readFileSync(file);
  const text = bytes.toString("utf8");
  if (!text.includes("_Py_stdlib_module_names")) {
    throw new Error(`${file} is not CPython's stdlib_module_names.h`);
  }
  const found = [...text.matchAll(/^"([A-Za-z_][A-Za-z0-9_]*)",$/gm)].map(
    (m) => m[1],
  );
  if (found.length < 200)
    throw new Error(`${file}: only ${found.length} names`);
  for (const n of found) names.add(n);
  sources.push(
    `// - ${tag}: https://github.com/python/cpython/blob/${tag}/Python/stdlib_module_names.h (${found.length} names, sha256 ${createHash("sha256").update(bytes).digest("hex")})`,
  );
}

const sorted = [...names].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
const out = [
  "// Generated by scripts/gen-python-stdlib.mjs. Do not edit.",
  "// The union of CPython's top-level standard-library module names from:",
  ...sources,
  "",
  "/** Top-level module names in the standard library of any CPython from 3.10 to 3.14. */",
  "export const STDLIB_MODULES: ReadonlySet<string> = new Set([",
  ...sorted.map((n) => `  ${JSON.stringify(n)},`),
  "]);",
  "",
].join("\n");
const target = path.join(
  root,
  "packages/adapters/python/src/stdlib.generated.ts",
);
writeFileSync(target, out);
process.stdout.write(
  `wrote ${path.relative(root, target)} (${sorted.length} modules)\n`,
);
