/**
 * pnpm bench <repo>... [--runs <n>] [--out <file>]
 *
 * Measures cold, warm-unchanged and incremental (1, 5, 50 edited files)
 * analysis time on copies of pinned checkouts (PLAN.md M2, Benchmark
 * protocol). Each analysis runs in its own Node process through the engine
 * with the SQLite cache, as the CLI does. The repositories are never
 * installed, built or run; edits are comment lines appended to copies.
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { performance } from "node:perf_hooks";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import type { AnalysisMeta } from "@epoch-dev/core";
import { typescriptAdapter } from "@epoch-dev/adapter-typescript";
import { RACY_MARGIN_NS, discover } from "@epoch-dev/engine";
import {
  hostInfo,
  median,
  repoInfo,
  table,
  writeReport,
  type RepoInfo,
} from "./report.js";

const RUN_ONCE = fileURLToPath(new URL("./run-once.js", import.meta.url));
const EDIT_SIZES = [1, 5, 50] as const;

interface Sample {
  readonly wallMs: number;
  readonly meta: AnalysisMeta;
}

interface Scenario {
  readonly name: string;
  readonly samples: readonly Sample[];
}

/** Deterministic PRNG (mulberry32), so every run edits the same files. */
function prng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function runOnce(dir: string, cacheDir: string): Sample {
  const t0 = performance.now();
  const r = spawnSync(process.execPath, [RUN_ONCE, dir], {
    encoding: "utf8",
    env: { ...process.env, EPOCH_CACHE_DIR: cacheDir },
    maxBuffer: 64 * 1024 * 1024,
  });
  const wallMs = performance.now() - t0;
  if (r.status !== 0) throw new Error(`analysis failed: ${r.stderr}`);
  const out = JSON.parse(r.stdout) as { meta: AnalysisMeta };
  return { wallMs, meta: out.meta };
}

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function measure(
  dir: string,
  runs: number,
): Promise<{ repo: RepoInfo; files: number; scenarios: Scenario[] }> {
  const repo = repoInfo(dir);
  const work = fs.mkdtempSync(path.join(os.tmpdir(), "epoch-bench-"));
  try {
    const copy = path.join(work, repo.name);
    fs.cpSync(repo.root, copy, {
      recursive: true,
      filter: (src) =>
        !/[\\/](?:\.git|node_modules)(?:[\\/]|$)/.test(
          src.slice(repo.root.length),
        ),
    });
    // Let the copy age past the racy-mtime margin, like a real checkout.
    await sleep(Number(RACY_MARGIN_NS / 1_000_000n) + 200);
    const isSource = (rel: string) =>
      typescriptAdapter.extensions.some((e) => rel.endsWith(e));
    const sources = discover(copy, { isSource }).files.filter(isSource);
    const scenarios: Scenario[] = [];
    let cacheN = 0;
    const freshCache = () => path.join(work, `cache-${String(cacheN++)}`);

    const cold: Sample[] = [];
    for (let i = 0; i < runs; i++) cold.push(runOnce(copy, freshCache()));
    scenarios.push({ name: "cold (empty cache)", samples: cold });

    const warmCache = freshCache();
    runOnce(copy, warmCache); // prime
    const warm: Sample[] = [];
    for (let i = 0; i < runs; i++) warm.push(runOnce(copy, warmCache));
    scenarios.push({ name: "warm, unchanged", samples: warm });

    for (const k of EDIT_SIZES) {
      const samples: Sample[] = [];
      for (let i = 0; i < runs; i++) {
        const next = prng(k * 1000 + i);
        const picked = new Set<string>();
        while (picked.size < Math.min(k, sources.length)) {
          picked.add(sources[Math.floor(next() * sources.length)] ?? "");
        }
        for (const rel of picked) {
          fs.appendFileSync(
            path.join(copy, rel),
            `\n// epoch-bench edit ${String(k)}/${String(i)}\n`,
          );
        }
        samples.push(runOnce(copy, warmCache));
      }
      scenarios.push({
        name: `incremental, ${String(k)} file${k === 1 ? "" : "s"} edited`,
        samples,
      });
    }
    return { repo, files: sources.length, scenarios };
  } finally {
    fs.rmSync(work, { recursive: true, force: true });
  }
}

const fmt = (ms: number) =>
  ms >= 1000 ? `${(ms / 1000).toFixed(2)} s` : `${ms.toFixed(0)} ms`;

function render(
  results: Awaited<ReturnType<typeof measure>>[],
  runs: number,
): string {
  const lines = [
    "# TypeScript/JavaScript analysis performance",
    "",
    "Generated by `pnpm bench` (packages/bench/src/perf.ts). Do not edit by hand.",
    "",
    "## Method",
    "",
    `- Each repository is a pinned shallow clone, copied to a temporary directory (without .git) and left to age past the ${String(Number(RACY_MARGIN_NS / 1_000_000_000n))} s racy-mtime margin, like a real checkout. It is never installed, built or run.`,
    "- Every analysis runs in a fresh Node process through the engine with the SQLite cache and serializes the canonical graph, as `epoch analyze --json` does. **Wall** includes process start-up; the stage columns come from AnalysisMeta.",
    `- **Cold:** an empty cache each run. **Warm:** the same cache, nothing changed. **Incremental:** comment lines appended to 1, 5 or 50 source files chosen by a fixed seed, then re-analyzed with the warm cache. Median of ${String(runs)} runs per scenario.`,
    "- Resolution and the graph are recomputed on every run by design (CLAUDE.md, ADR-004), so they bound warm and incremental runs.",
    "- **Files parsed** are cache misses. **Files re-hashed** were read because the manifest could not vouch for them; it exceeds the edited count because files edited just before the previous run are still inside the racy margin and are hashed once more (then hit the cache).",
    `- **Host:** ${hostInfo()}.`,
    "",
  ];
  for (const r of results) {
    lines.push(
      `## ${r.repo.name}`,
      "",
      `${r.repo.url ?? r.repo.name} at \`${r.repo.commit ?? "unknown"}\`, ${String(r.files)} TS/JS files.`,
      "",
    );
    lines.push(
      table(
        [
          "Scenario",
          "Wall",
          "Analysis",
          "Discover",
          "Changes",
          "Parse",
          "Resolve",
          "Graph",
          "Files parsed",
          "Files re-hashed",
        ],
        r.scenarios.map((s) => {
          const m = (f: (x: Sample) => number) => median(s.samples.map(f));
          return [
            s.name,
            fmt(m((x) => x.wallMs)),
            fmt(m((x) => x.meta.timingsMs.total)),
            fmt(m((x) => x.meta.timingsMs.discover)),
            fmt(m((x) => x.meta.timingsMs.changes)),
            fmt(m((x) => x.meta.timingsMs.parse)),
            fmt(m((x) => x.meta.timingsMs.resolve)),
            fmt(m((x) => x.meta.timingsMs.graph)),
            String(m((x) => x.meta.counts.cacheMisses)),
            String(m((x) => x.meta.counts.rehashed)),
          ];
        }),
      ),
      "",
    );
  }
  return lines.join("\n");
}

async function main(): Promise<void> {
  const { values, positionals } = parseArgs({
    options: {
      runs: { type: "string", default: "5" },
      out: {
        type: "string",
        default: "docs/benchmarks/typescript-performance.md",
      },
    },
    allowPositionals: true,
  });
  const runs = Number(values.runs);
  if (positionals.length === 0 || !Number.isInteger(runs) || runs < 1) {
    process.stderr.write(
      "usage: pnpm bench <repo>... [--runs <n>] [--out <file>]\n",
    );
    process.exitCode = 1;
    return;
  }
  const results = [];
  for (const dir of positionals) {
    process.stderr.write(`benchmarking ${dir}...\n`);
    results.push(await measure(dir, runs));
  }
  writeReport(path.resolve(values.out), render(results, runs));
}

await main();
