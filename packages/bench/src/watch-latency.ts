/**
 * pnpm bench:watch <repo>... [--churn <full-history clone>]... [--runs 3] [--out <file>]
 *
 * Watcher latency (M4): on a temporary copy of each repository, the time from
 * writing a change to a source file until the watcher delivers the updated
 * graph (the batch's 300 ms quiet period included), with the app's options
 * (cache, churn memo). Plus the cost of the 90-day churn query on a
 * full-history clone. The repositories are never installed, built or run.
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { performance } from "node:perf_hooks";
import { parseArgs } from "node:util";
import {
  ChurnMemo,
  FsReader,
  MemoryCacheStore,
  analyze,
  gitChurn,
  toPosix,
  watchProject,
  type AnalyzeResult,
} from "@epoch-dev/engine";
import {
  hostInfo,
  median,
  repoInfo,
  table,
  writeReport,
  type RepoInfo,
} from "./report.js";

interface WatchResult {
  readonly repo: RepoInfo;
  readonly file: string;
  readonly nodes: number;
  /** Write to delivered update, per run. */
  readonly latencyMs: readonly number[];
  /** The re-analysis alone (AnalysisMeta total), per run. */
  readonly analyzeMs: readonly number[];
}

/** The first source file in sorted order with this extension, outside tests. */
function pickFile(graph: AnalyzeResult["graph"]): string {
  const candidates = graph.nodes
    .filter(
      (n) =>
        n.kind === "file" &&
        (n.language === "typescript" || n.language === "python") &&
        !/(?:^|\/)(?:tests?|__tests__)\//.test(n.id) &&
        n.metrics.fanIn > 0,
    )
    .map((n) => n.id);
  const [first] = candidates;
  if (first === undefined) throw new Error("no source file with dependents");
  return first;
}

async function measureWatch(dir: string, runs: number): Promise<WatchResult> {
  const repo = repoInfo(dir);
  const copy = toPosix(
    fs.realpathSync.native(
      fs.mkdtempSync(path.join(os.tmpdir(), "epoch-bench-watch-")),
    ),
  );
  fs.cpSync(repo.root, copy, { recursive: true });
  try {
    const options = {
      cache: new MemoryCacheStore(),
      churnMemo: new ChurnMemo(),
    };
    const initial = await analyze(copy, options);
    const file = pickFile(initial.graph);
    let waiting: ((r: AnalyzeResult) => void) | undefined;
    const watcher = await watchProject(initial, {
      analyze: options,
      onUpdate: (r) => waiting?.(r),
    });
    const latencyMs: number[] = [];
    const analyzeMs: number[] = [];
    try {
      for (let i = 0; i < runs; i++) {
        const updated = new Promise<AnalyzeResult>((resolve) => {
          waiting = resolve;
        });
        const started = performance.now();
        // A new top-level statement: the file's facts change, the graph may not.
        fs.appendFileSync(
          path.join(copy, file),
          file.endsWith(".py")
            ? `\nEPOCH_BENCH_${String(i)} = ${String(i)}\n`
            : `\nexport const EPOCH_BENCH_${String(i)} = ${String(i)};\n`,
        );
        const result = await updated;
        latencyMs.push(performance.now() - started);
        analyzeMs.push(result.meta.timingsMs.total);
        // Let the tree settle between runs.
        await new Promise((r) => setTimeout(r, 1000));
      }
    } finally {
      await watcher.close();
    }
    return {
      repo,
      file,
      nodes: initial.graph.nodes.length,
      latencyMs,
      analyzeMs,
    };
  } finally {
    fs.rmSync(copy, { recursive: true, force: true });
  }
}

async function main(): Promise<void> {
  const { values, positionals } = parseArgs({
    options: {
      churn: { type: "string", multiple: true, default: [] },
      runs: { type: "string", default: "3" },
      out: { type: "string", default: "docs/benchmarks/watcher.md" },
    },
    allowPositionals: true,
  });
  const runs = Number(values.runs);
  const results: WatchResult[] = [];
  for (const dir of positionals) {
    process.stderr.write(`watching ${dir}...\n`);
    results.push(await measureWatch(dir, runs));
  }
  const churn = values.churn.map((dir) => {
    const repo = repoInfo(dir);
    const ms: number[] = [];
    let commits = 0;
    let files = 0;
    for (let i = 0; i < runs; i++) {
      const t = performance.now();
      const c = gitChurn(repo.root, new FsReader(repo.root));
      ms.push(performance.now() - t);
      const all = new Set<string>();
      for (const set of c.commits.values()) for (const h of set) all.add(h);
      commits = all.size;
      files = c.commits.size;
    }
    return { repo, ms, commits, files };
  });

  const fmt = (xs: readonly number[]) =>
    xs.map((x) => `${(x / 1000).toFixed(2)} s`).join(", ");
  const report = [
    "# File watcher latency and churn cost",
    "",
    "Generated by `pnpm bench:watch` (packages/bench/src/watch-latency.ts). Do not edit by hand.",
    "",
    "## Method",
    "",
    "- **Latency:** a temporary copy of each repository (with its `.git`) is analyzed once with a memory cache and the churn memo, as the app does; then the watcher runs with the app's settings (300 ms quiet, 2 s at most per batch). Each run appends one top-level statement to the same source file (the first file with dependents in sorted order, outside tests) and measures from the write until the watcher delivers the re-analyzed graph. One second passes between runs.",
    "- **Latency includes** the operating system's event delivery, the 300 ms quiet period, the incremental analysis (only the edited file is parsed again; resolution and the graph are recomputed, ADR-004) and the Score stage (the churn memo is reused, as HEAD does not move).",
    "- **Churn cost:** `git log` over the 90 days before HEAD (the Score stage's query), on a clone with full history, timed in-process.",
    `- **Host:** ${hostInfo()}.`,
    "",
    "## Latency",
    "",
    results.length === 0
      ? "Not measured."
      : table(
          [
            "Repository",
            "Commit",
            "Nodes",
            "Edited file",
            "Write to update",
            "Median",
            "Re-analysis alone",
          ],
          results.map((r) => [
            r.repo.url ?? r.repo.name,
            r.repo.commit?.slice(0, 12) ?? "unknown",
            String(r.nodes),
            r.file,
            fmt(r.latencyMs),
            `${(median(r.latencyMs) / 1000).toFixed(2)} s`,
            fmt(r.analyzeMs),
          ]),
        ),
    "",
    "## Churn cost",
    "",
    churn.length === 0
      ? "Not measured."
      : table(
          [
            "Repository",
            "Commit",
            "Commits in the window",
            "Files touched",
            "Time per run",
          ],
          churn.map((c) => [
            c.repo.url ?? c.repo.name,
            c.repo.commit?.slice(0, 12) ?? "unknown",
            String(c.commits),
            String(c.files),
            fmt(c.ms),
          ]),
        ),
    "",
  ].join("\n");
  writeReport(path.resolve(values.out), report);
  process.stdout.write(`${report}\nwrote ${values.out}\n`);
}

await main();
