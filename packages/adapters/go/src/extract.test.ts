import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { Language, Parser } from "web-tree-sitter";
import { EMPTY_EXTRACTOR_CONFIG, type FileFacts } from "@epoch-dev/core";
import { extract } from "./extract.js";
import { grammarFor, isPackageFile, isTestFile, languageFor } from "./files.js";

await Parser.init();
const go = await Language.load(
  fs.readFileSync(
    path.join(
      path.dirname(
        createRequire(import.meta.url).resolve(
          "@vscode/tree-sitter-wasm/package.json",
        ),
      ),
      "wasm",
      "tree-sitter-go.wasm",
    ),
  ),
);

function facts(text: string, file = "a/a.go"): FileFacts {
  const parser = new Parser();
  parser.setLanguage(go);
  const tree = parser.parse(text);
  if (!tree) throw new Error("parse failed");
  try {
    return extract({ path: file, text, tree }, EMPTY_EXTRACTOR_CONFIG);
  } finally {
    tree.delete();
    parser.delete();
  }
}

const lines = (...ls: string[]) => `${ls.join("\n")}\n`;

describe("extract: imports", () => {
  it("reads single, grouped, aliased, dot, blank and raw-string imports", () => {
    const f = facts(
      lines(
        "package a",
        "",
        'import "fmt"',
        "import (",
        '\tal "example.com/x/alias" // why',
        '\t. "example.com/x/dot"',
        '\t_ "example.com/x/blank"',
        "\t`example.com/x/raw`",
        ")",
      ),
    );
    expect(
      f.imports.map((i) => [i.kind, i.specifier, i.names.length, i.line]),
    ).toEqual([
      ["static", "fmt", 1, 3],
      ["static", "example.com/x/alias", 1, 5],
      ["static", "example.com/x/dot", 1, 6],
      ["side-effect", "example.com/x/blank", 0, 7],
      ["static", "example.com/x/raw", 1, 8],
    ]);
    expect(f.imports.every((i) => !i.typeOnly)).toBe(true);
  });

  it('decodes escapes in interpreted strings and keeps cgo\'s import "C"', () => {
    const f = facts(
      lines(
        "package a",
        "",
        "// #include <stdio.h>",
        'import "C"',
        'import "a\\u0062c"',
      ),
    );
    expect(f.imports.map((i) => i.specifier)).toEqual(["C", "abc"]);
  });
});

describe("extract: exports and markers", () => {
  it("lists exported package-level names, not methods, fields or unexported names", () => {
    const f = facts(
      lines(
        "package a",
        "",
        "type T struct{ Field int }",
        "type (",
        "\tU int",
        "\tAlias = int",
        "\tlower int",
        ")",
        "type G[K any] struct{}",
        "func F() {}",
        "func (T) Method() {}",
        "func g() {}",
        "const A, b = 1, 2",
        "const (",
        "\tC = iota",
        "\td",
        ")",
        "var V, W = 1, 2",
        "var (",
        "\tX int",
        "\ty int",
        ")",
        "var _ = 3",
        "var Écran = 1",
      ),
    );
    expect(f.exports.map((e) => e.name)).toEqual([
      "T",
      "U",
      "Alias",
      "G",
      "F",
      "A",
      "C",
      "V",
      "W",
      "X",
      "Écran",
    ]);
  });

  it("recognizes the generated-file marker only before the package clause", () => {
    const marker = "// Code generated by stringer. DO NOT EDIT.";
    expect(facts(lines(marker, "", "package a")).isGenerated).toBe(true);
    expect(
      facts(lines("//go:build linux", "", marker, "package a")).isGenerated,
    ).toBe(true);
    expect(facts(`${marker}\r\n\r\npackage a\r\n`).isGenerated).toBe(true);
    expect(facts(lines("package a", "", marker)).isGenerated).toBe(false);
    expect(
      facts(lines("// Code generated by hand. Edit freely.", "package a"))
        .isGenerated,
    ).toBe(false);
  });

  it("counts non-blank lines", () => {
    expect(facts(lines("package a", "", "", "func F() {}")).loc).toBe(2);
  });
});

describe("extract: key-like strings", () => {
  it("keeps interpreted and raw key-like literals, not import paths or prose", () => {
    const f = facts(
      lines(
        "package main",
        "",
        "import (",
        '\t"fmt"',
        '\t"net/http"',
        ")",
        "",
        "func main() {",
        '\thttp.HandleFunc("/api/users/{id}", nil)',
        '\tfmt.Println("hello world")',
        "\tpublish(`orders.created`)",
        "}",
      ),
      "main.go",
    );
    expect(f.strings).toEqual(["/api/users/{id}", "orders.created"]);
  });
});

describe("files", () => {
  it("analyzes .go files the go tool builds", () => {
    expect(grammarFor("cmd/x/main.go")).toBe("go");
    expect(languageFor("cmd/x/main.go")).toBe("go");
    for (const p of [
      "vendor/github.com/x/y.go",
      "a/testdata/fixture.go",
      "_tools/gen.go",
      "a/_skip.go",
      ".hidden/h.go",
      "a/.x.go",
      "a/b.txt",
    ]) {
      expect(isPackageFile(p), p).toBe(false);
    }
  });

  it("treats _test.go files as tests", () => {
    expect(isTestFile("a/a_test.go")).toBe(true);
    expect(isTestFile("a/test.go")).toBe(false);
    expect(isTestFile("a/contest.go")).toBe(false);
  });
});
